import { homedir } from "node:os"
import path from "node:path"
import { pathToFileURL } from "node:url"

// Read the installed service, not a possibly older Iradah development checkout.
const source = process.env.HUB_SHELL_SOURCE ?? (await installedSource())
const { hubHtml } = await import(pathToFileURL(source).href)
const html = hubHtml("<html><head></head><body><!--opencode--></body></html>", "/")
const head = html.match(/<head>([\s\S]*?)<\/head>/)?.[1].replace(/<link\b[^>]*>/g, "")
const body = html.match(/<body[^>]*>([\s\S]*?)<!--opencode-->/)?.[1]
const footer = html.match(/<!--opencode-->([\s\S]*?)<\/body>/)?.[1]
if (!head || !body || !footer) throw new Error("Installed Hub shell has changed shape; review its integration")
const output = `// Generated by bun run sync:hub from the installed Flow gateway. Do not edit.\n// prettier-ignore\nexport const shell = ${JSON.stringify({ head, body, footer }, null, 2)}\n`
const target = Bun.file(new URL("./src/hub-shell.ts", import.meta.url))
if (process.argv.includes("--check")) {
  if ((await target.text()) !== output) {
    throw new Error(
      "Hub shell is out of sync with Flow/Orchestrator. Run bun run sync:hub, review and verify before deploying.",
    )
  }
  console.log("Hub shell matches the installed Flow/Orchestrator shell")
  process.exit(0)
}
await Bun.write(target, output)
console.log("Updated OpenCode's shared Hub shell; review safe-area overrides and run the Worker tests")

async function installedSource() {
  const child = Bun.spawn([
    "plutil",
    "-extract",
    "WorkingDirectory",
    "raw",
    "-o",
    "-",
    path.join(homedir(), "Library/LaunchAgents/com.iradah.flow-atlas.plist"),
  ])
  const directory = (await new Response(child.stdout).text()).trim()
  if ((await child.exited) !== 0)
    throw new Error("Cannot locate installed Flow; set HUB_SHELL_SOURCE to its server/hub.mjs")
  return path.join(directory, "packages/feature-map/server/hub.mjs")
}
